/* Recommended activities for a given age */
export function getRecommendedActivities(age, completedIds = []) {
  const all = Object.values(ACTIVITIES).filter(a => {
    const [min, max] = a.ageRange
    return age >= min && age <= max && a.implemented
  })
  const uncompleted = all.filter(a => !completedIds.includes(a.id))
  return uncompleted.length > 0 ? uncompleted.slice(0, 4) : all.slice(0, 4)
}

